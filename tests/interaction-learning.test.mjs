function diagonalColorExample(shift = 0) {
  const width = 100, height = 80
  const source = new Uint8ClampedArray(width * height * 4).fill(255)
  const automatic = new Uint8ClampedArray(width * height * 4)
  const corrected = new Uint8ClampedArray(width * height * 4)
  // Blue diagonal curve missed by automatic detector
  for (let step = 0; step < 50; step++) {
    const x = 15 + step + shift
    const y = 12 + step
    if (x < width && y < height) {
      const offset = (y * width + x) * 4
      source[offset] = 10; source[offset + 1] = 80; source[offset + 2] = 240; source[offset + 3] = 255
      corrected[offset + 3] = 255
    }
  }
  // Black vertical grid remnant wrongly included by automatic detector
  for (let y = 10; y < 65; y++) {
    const x = 85 - shift
    const offset = (y * width + x) * 4
    source[offset] = 15; source[offset + 1] = 15; source[offset + 2] = 15; source[offset + 3] = 255
    automatic[offset + 3] = 255
  }
  return { pixels: { width, height, source, automatic }, corrected }
}

test('validates interaction models and tracks interaction totals', () => {
  const model = initialInteractionModel()
  assert.equal(isValidInteractionModel(model), true)
  assert.equal(totalInteractionCount(model), 0)
  assert.equal(isValidInteractionModel({ ...model, featureWeights: [1, 2] }), false)
  assert.equal(isValidInteractionModel({ ...model, snapRadius: 999 }), false)
  assert.equal(isValidInteractionModel({ ...model, spacingFactor: 0.1 }), false)
})

test('learns denser spacing from inserted manual points and sparser spacing from thinned deletions', () => {
  let model = initialInteractionModel()
  const pointsAfter = [{ x: 10, y: 50 }, { x: 30, y: 20 }, { x: 50, y: 50 }]
  for (let i = 0; i < 4; i++) {
    model = learnFromPointAdded(model, { point: pointsAfter[1], insertedIndex: 1, pointsAfter })
  }
  assert.equal(model.stats.pointsAdded, 4)
  assert.ok(model.spacingFactor < 1, `expected denser spacingFactor < 1, got ${model.spacingFactor}`)
  assert.ok(model.curvatureBias > 1, `expected higher curvatureBias on sharp bend, got ${model.curvatureBias}`)
  assert.ok(effectiveSampleStep(20, 1, model) < 20)

  let sparseModel = initialInteractionModel()
  for (let i = 0; i < 5; i++) {
    sparseModel = learnFromPointDeleted(sparseModel, {
      removed: { x: 30, y: 50.5 },
      prev: { x: 10, y: 50 },
      next: { x: 50, y: 51 },
      wasAutoGenerated: true,
    })
  }
  assert.equal(sparseModel.stats.pointsDeleted, 5)
  assert.ok(sparseModel.spacingFactor > 1, `expected sparser spacingFactor > 1, got ${sparseModel.spacingFactor}`)
})

test('learns snap radius and pixel confidence from point moves and snap corrections', () => {
  const { pixels } = diagonalColorExample()
  let model = initialInteractionModel()

  // Micro jitter is ignored
  const unchanged = learnFromPointMoved(model, { from: { x: 20, y: 17 }, to: { x: 20.5, y: 17.5 }, pixels })
  assert.equal(unchanged, model)

  // Moving a point from grid remnant onto the blue diagonal curve trains rich weights & adapts snap radius
  const beforeCurveScore = predictRichPixelScore(model, pixels, 35, 32)
  for (let step = 0; step < 8; step++) {
    model = learnFromPointMoved(model, {
      from: { x: 85, y: 20 + step * 3 },
      to: { x: 25 + step * 3, y: 22 + step * 3 },
      pixels,
    })
  }
  const afterCurveScore = predictRichPixelScore(model, pixels, 35, 32)
  assert.equal(model.stats.pointsMoved, 8)
  assert.ok(model.featureSamples >= 8)
  assert.ok(afterCurveScore > beforeCurveScore, `expected curve score to improve (${beforeCurveScore} -> ${afterCurveScore})`)

  // Snapping points adapts snap radius cleanly
  const snappedModel = learnFromPointsSnapped(model, {
    displacements: [
      { from: { x: 30, y: 31 }, to: { x: 30, y: 27 }, distance: 4 },
      { from: { x: 35, y: 37 }, to: { x: 35, y: 32 }, distance: 5 },
    ],
    pixels,
  })
  assert.equal(snappedModel.stats.pointsSnapped, 2)
  assert.ok(snappedModel.snapRadius < model.snapRadius)
})

test('learns preferred gap healing style from repeated user selections', () => {
  let model = initialInteractionModel()
  assert.equal(preferredHealingChoice(model), 0)
  model = learnFromHealingApplied(model, 2)
  model = learnFromHealingApplied(model, 2)
  assert.equal(preferredHealingChoice(model), 2)
  assert.equal(model.stats.healingApplied, 2)
})

test('upgraded 14-feature model learns diagonal colored curves and predicts refinements accurately', () => {
  let model = initialInteractionModel()
  for (let shift = 0; shift < 4; shift++) {
    const sample = diagonalColorExample(shift)
    model = learnFromLayerComparison(model, sample.pixels, sample.corrected, 'reconstruction')
  }
  assert.equal(model.stats.reconstructionEdits, 4)

  const heldOut = diagonalColorExample(5)
  const prediction = predictEnhancedLearningEdits(initialLearningModel(), model, heldOut.pixels)
  let addedRight = 0, erasedRight = 0, mistakes = 0
  for (let index = 0; index < prediction.add.length; index++) {
    const target = heldOut.corrected[index * 4 + 3] >= 64
    if (prediction.add[index]) target ? addedRight++ : mistakes++
    if (prediction.erase[index]) target ? mistakes++ : erasedRight++
  }
  assert.ok(addedRight >= 25, `expected >= 25 diagonal curve additions, got ${addedRight}`)
  assert.ok(erasedRight >= 25, `expected >= 25 grid remnant erasures, got ${erasedRight}`)
  assert.equal(mistakes, 0)
})

test('createInteractionUpdatePayload creates bounded sync deltas and validates payloads', () => {
  const before = initialInteractionModel()
  assert.equal(createInteractionUpdatePayload(before, before), null)
  const after = learnFromHealingApplied(before, 2)
  const payload = createInteractionUpdatePayload(before, after, 2)
  assert.ok(payload)
  assert.equal(isValidInteractionUpdatePayload(payload), true)
  assert.equal(payload.healingChoice, 2)
  assert.equal(payload.statsDelta.healingApplied, 1)
  assert.equal(isValidInteractionUpdatePayload({ ...payload, featureDelta: [99] }), false)
})
